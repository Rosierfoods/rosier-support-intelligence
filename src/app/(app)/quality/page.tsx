import Link from 'next/link';
import { requirePermission } from '@/lib/auth/session';
import { withOrg } from '@/lib/db';
import { parsePage, withParams, type SP } from '@/lib/filters';
import { FLAG_KPI_DEFS, flagFilterOptions, flagKpis, listFlags, parseFlagFilters } from '@/lib/repos/flags';
import { Badge, Card, DemoBadge, EmptyState, KpiCard, Notice, PageHeader, Table, TBody, THead } from '@/components/ui';
import { ChannelBadge, FlagStatusBadge, SeverityBadge } from '@/components/badges';
import { ClearFilters, ParamSelect, RangeFilter } from '@/components/filters';
import { Pagination } from '@/components/pagination';
import { FlagActions } from '@/components/interaction/FlagActions';
import { BulkFlagBar } from '@/components/interaction/BulkFlagBar';
import { BULK_FORM_ID } from '@/components/interaction/types';
import { CHANNELS, CHANNEL_LABELS, FLAG_STATUSES, FLAG_STATUS_LABELS, SEVERITIES } from '@/lib/constants';
import { fmtDateTime, fmtMs, fmtNum, fmtPct, relTime, titleCase } from '@/lib/format';
import { bulkFlagAction, flagAction } from './actions';

export const metadata = { title: 'AI Quality Monitoring' };

export default async function QualityPage(props: { searchParams: Promise<SP> }) {
  const searchParams = await props.searchParams;
  const s = await requirePermission('flags.review');
  const f = parseFlagFilters(searchParams);
  const { page, pageSize, offset } = parsePage(searchParams, 25);
  const { list, kpis, opts } = await withOrg(s.org.id, async (db) => ({
    list: await listFlags(db, s, f, { pageSize, offset }),
    kpis: await flagKpis(db, s, f),
    opts: await flagFilterOptions(db, s),
  }));
  const canReview = s.permissions.has('flags.review');
  const canAssign = s.permissions.has('flags.assign');
  const canCoach = s.permissions.has('coaching.assign');
  const reviewers = opts.reviewers.map((r) => ({ id: r.id, name: r.name }));
  const sevHref = (sev: string) => `/quality${withParams(searchParams, { page: undefined, severity: sev, status: 'open' })}`;
  const hasDemo = list.rows.some((r) => r.is_demo);

  return (
    <div className="space-y-4">
      <PageHeader title="AI Quality Monitoring"
        description={<>Review queue for AI-raised quality alerts · {f.range.label}{hasDemo && <> · <DemoBadge /></>}</>}
        actions={<RangeFilter defaultPreset="all" />} />

      <Notice tone="warn" title="AI flags are potential concerns. Confirm evidence before any consequential decision.">
        Alerts are generated by an AI model and can be wrong. Open the evidence, check it against the approved SOP, and record your decision.
        No disciplinary or employment action may be taken on the basis of an AI flag alone.
      </Notice>

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-7">
        {SEVERITIES.map((sev) => (
          <KpiCard key={sev} label={`Open ${sev}`} value={fmtNum(kpis.open[sev])} tone={sev === 'critical' && kpis.open[sev] ? 'bad' : sev === 'high' && kpis.open[sev] ? 'warn' : undefined}
            formula={FLAG_KPI_DEFS.open} href={sevHref(sev)} />
        ))}
        <KpiCard label="New in range" value={fmtNum(kpis.newInRange)} formula={FLAG_KPI_DEFS.newInRange} sub={`${fmtNum(kpis.escalatedOpen)} escalated & open`} />
        <KpiCard label="Confirmed rate" value={fmtPct(kpis.confirmedRate, 0)} sub={`${fmtNum(kpis.decided)} decided`} formula={FLAG_KPI_DEFS.confirmedRate} />
        <KpiCard label="False-positive rate" value={fmtPct(kpis.fpRate, 0)} tone={(kpis.fpRate ?? 0) > 0.3 ? 'warn' : undefined}
          sub="High rates → tune alert rules" formula={FLAG_KPI_DEFS.fpRate} href={`/quality${withParams(searchParams, { page: undefined, severity: undefined, status: 'false_positive' })}`} />
      </div>

      <Card className="p-3">
        <div className="flex flex-wrap items-center gap-2">
          <ParamSelect name="status" placeholder="Any status" options={[{ value: 'open', label: 'Open (new, under review, confirmed)' },
            ...FLAG_STATUSES.map((st) => ({ value: st, label: FLAG_STATUS_LABELS[st] }))]} />
          <ParamSelect name="severity" placeholder="Any severity" options={SEVERITIES.map((v) => ({ value: v, label: titleCase(v) }))} />
          <ParamSelect name="rule" placeholder="Any rule" className="max-w-[16rem]" options={opts.rules.map((r) => ({ value: r.code, label: `${titleCase(r.severity)} · ${r.name}` }))} />
          <ParamSelect name="agent" placeholder="Any agent" options={opts.agents.map((a) => ({ value: a.id, label: a.name }))} />
          <ParamSelect name="channel" placeholder="Any channel" options={CHANNELS.map((c) => ({ value: c, label: CHANNEL_LABELS[c] }))} />
          <ParamSelect name="assignee" placeholder="Any assignee" options={[{ value: 'me', label: 'Assigned to me' }, { value: 'unassigned', label: 'Unassigned' },
            ...reviewers.map((r) => ({ value: r.id, label: r.name }))]} />
          <ParamSelect name="escalated" placeholder="Escalated or not" options={[{ value: '1', label: 'Escalated only' }]} />
          <ClearFilters />
        </div>
      </Card>

      <Card>
        <BulkFlagBar action={bulkFlagAction} reviewers={reviewers} canReview={canReview} canAssign={canAssign} />
        {list.rows.length ? (
          <Table>
            <THead>
              <tr>
                <th className="th w-8"><span className="sr-only">Select</span></th>
                <th className="th">Alert</th>
                <th className="th">Evidence excerpt</th>
                <th className="th">Agent / interaction</th>
                <th className="th">Confidence</th>
                <th className="th">Status</th>
                <th className="th">Assignee</th>
                <th className="th"><span className="sr-only">Actions</span></th>
              </tr>
            </THead>
            <TBody>
              {list.rows.map((r) => {
                const ev = r.evidence_ref ?? {};
                const when = typeof ev.start_ms === 'number' ? `at ${fmtMs(ev.start_ms)}` : ev.sent_at ? fmtDateTime(ev.sent_at) : null;
                const href = `/inbox/${r.interaction_id}?flag=${r.id}#evidence`;
                return (
                  <tr key={r.id} className="hover:bg-brand-50/40">
                    <td className="td"><input type="checkbox" name="ids" value={r.id} form={BULK_FORM_ID} className="mt-1 accent-[#784900]" aria-label={`Select alert ${r.title} on ${r.ref}`} /></td>
                    <td className="td min-w-[14rem] max-w-[18rem]">
                      <div className="flex flex-wrap items-center gap-1"><SeverityBadge severity={r.severity} />{r.escalated && <Badge tone="warn">Escalated</Badge>}{r.is_demo && <DemoBadge />}</div>
                      <Link href={href} className="mt-1 block text-[13px] font-medium text-ink hover:text-brand">{r.title}</Link>
                      <p className="text-2xs text-ink-muted">{r.criterion_name ? `Criterion: ${r.criterion_name} · ` : ''}{relTime(r.created_at)}</p>
                      {r.primary_issue && <p className="text-2xs text-ink-faint">Issue: {r.primary_issue}</p>}
                    </td>
                    <td className="td min-w-[16rem] max-w-[24rem]">
                      <Link href={href} className="block rounded-md border-l-2 border-amber-300 pl-2 text-[13px] italic text-ink hover:bg-amber-50/50">
                        <span className="line-clamp-3">“{r.excerpt}”</span>
                      </Link>
                      <p className="mt-1 line-clamp-2 text-2xs text-ink-muted" title={r.reason}><span className="font-medium">AI reason:</span> {r.reason}</p>
                      {when && <p className="text-2xs text-ink-faint">{when}</p>}
                    </td>
                    <td className="td whitespace-nowrap">
                      {r.agent_id ? <Link href={`/agents/${r.agent_id}`} className="text-ink hover:text-brand">{r.agent_name}</Link> : <span className="text-ink-faint">Unknown agent</span>}
                      <p className="text-2xs text-ink-muted"><Link href={href} className="hover:text-brand">{r.ref}</Link></p>
                      <ChannelBadge channel={r.channel} platform={r.source_platform} />
                    </td>
                    <td className="td tabular-nums">{r.confidence ? fmtPct(Number(r.confidence), 0) : '—'}</td>
                    <td className="td"><FlagStatusBadge status={r.status} /></td>
                    <td className="td whitespace-nowrap text-ink-muted">{r.assignee_name ?? <span className="text-ink-faint">Unassigned</span>}</td>
                    <td className="td text-right">
                      <FlagActions compact flag={{ id: r.id, status: r.status, escalated: r.escalated, assigned_to: r.assigned_to }} action={flagAction} canReview={canReview} canAssign={canAssign} canCoach={canCoach} reviewers={reviewers} />
                    </td>
                  </tr>
                );
              })}
            </TBody>
          </Table>
        ) : (
          <EmptyState title="No alerts match these filters" description="Great news — or try widening the date range and status filters."
            action={<Link href="/quality" className="text-sm text-brand hover:underline">Reset filters</Link>} />
        )}
        <Pagination searchParams={searchParams} page={page} pageSize={pageSize} total={list.total} basePath="/quality" />
      </Card>
    </div>
  );
}
